pub fn simulate() {
  let mut sim = Simulator::new();
  let simulators: Vec<fn(&mut Simulator)> = vec![
    Simulator::simulate_FetchStageInstance,
    Simulator::simulate_DecodeStageInstance,
    Simulator::simulate_ExecuteStageInstance,
    Simulator::simulate_MemoryStageInstance,
    Simulator::simulate_WriteBackStageInstance,
    Simulator::simulate_Driver,
  ];
  let downstreams: Vec<fn(&mut Simulator)> =
    vec![Simulator::simulate_SRAM, Simulator::simulate_HazardUnit];
  load_hex_file(&mut sim.SRAM_val.payload, "data.hex");

  for i in 1..=2500 {
    sim.Driver_event.push_back(i * 100);
  }
  let mut idle_count = 0;
  for i in 1..=2500 {
    sim.stamp = i * 100;
    sim.reset_downstream();

    for simulate in simulators.iter() {
      simulate(&mut sim);
    }

    for simulate in downstreams.iter() {
      simulate(&mut sim);
    }

    let any_module_triggered = sim.FetchStageInstance_triggered
      || sim.DecodeStageInstance_triggered
      || sim.ExecuteStageInstance_triggered
      || sim.MemoryStageInstance_triggered
      || sim.WriteBackStageInstance_triggered
      || sim.Driver_triggered;

    // Handle idle threshold
    if !any_module_triggered {
      idle_count += 1;
      if idle_count >= 100 {
        println!("Simulation stopped due to reaching idle threshold of 100");
        break;
      }
    } else {
      idle_count = 0;
    }

    sim.stamp += 50;
    sim.tick_registers();
    sim.reset_dram();
    unsafe {
      // Tick all DRAM memory interfaces
    }
  }
}
